#!/usr/bin/env python3
"""Pointer shapes for RetroWrite II (DHGR pixels are narrow, so shapes are
drawn about twice as wide as tall-pixel art). '#' black, 'o' white, '.' clear."""
import sys
ARROW = [
"oo..............",
"o##o............",
"o####o..........",
"o######o........",
"o########o......",
"o##########o....",
"o############o..",
"o########ooooo..",
"o####o###o......",
"o##oo.o###o.....",
"oo....o###o.....",
".......o###o....",
".......o###o....",
"........ooo.....",
"................",
"................",
]
IBEAM = [
"oooo.oooo.......",
"o###o###o.......",
"oooo#oooo.......",
"...o#o..........",
"...o#o..........",
"...o#o..........",
"...o#o..........",
"...o#o..........",
"...o#o..........",
"...o#o..........",
"oooo#oooo.......",
"o###o###o.......",
"oooo.oooo.......",
"................",
"................",
"................",
]
WATCH = [
"..oooooooooo....",
"..o########o....",
"..oo######oo....",
"...oo####oo.....",
"....oo##oo......",
".....o##o.......",
"....oo##oo......",
"...oo#oo#oo.....",
"..oo#oooo#oo....",
"..o###oo###o....",
"..o########o....",
"..oooooooooo....",
"................",
"................",
"................",
"................",
]
HOT = {'arrow': (0, 0), 'ibeam': (4, 6), 'watch': (7, 6)}

def enc(rows):
    out = []
    for r in rows:
        m = sum(1 << i for i, c in enumerate(r) if c in '#o')
        w = sum(1 << i for i, c in enumerate(r) if c == 'o')
        out += [m & 0xFF, m >> 8, w & 0xFF, w >> 8]
    return out

lines = ['; generated by mkptr.py']
for name, rows in (('arrow', ARROW), ('ibeam', IBEAM), ('watch', WATCH)):
    b = enc(rows)
    lines.append(f'{name}:')
    for i in range(0, len(b), 16):
        lines.append('        .byte   ' + ','.join(f'${x:02X}' for x in b[i:i + 16]))
lines.append('hotx:   .byte   ' + ','.join(str(HOT[n][0]) for n in ('arrow', 'ibeam', 'watch')))
lines.append('hoty:   .byte   ' + ','.join(str(HOT[n][1]) for n in ('arrow', 'ibeam', 'watch')))
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
