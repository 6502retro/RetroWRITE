# RetroWrite II "Sans" - an original bitmap font for the Apple II double
# hi-res screen (560 x 192, pixels about 2.2x taller than wide).
# Each glyph: list of 10 rows (row 7 sits on the baseline, rows 8-9 are
# descenders). Vertical strokes are two pixels wide.
B = '.'
def g(*rows, top=1):
    """rows starting at row `top`; pads to 10 rows"""
    w = len(rows[0])
    out = [B * w] * top + list(rows)
    out += [B * w] * (10 - len(out))
    assert all(len(r) == w for r in out), rows
    return out

