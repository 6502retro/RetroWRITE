#!/usr/bin/env python3
"""Compile RetroWrite fonts into a ca65 source file.

Font layout (all offsets relative to the font label):
  +0      height in rows (10)
  +1      ascent (rows above the baseline, inclusive) (8)
  +2      width[100]     chars $20..$83, in pixels (without the 1px gap),
                         bits 6-7 hold bits 8-9 of the bitmap offset;
                         $7F-$83 are interface symbols (apple, check, icons)
  +102    offset_lo[100] offset of the glyph bitmap from the font's bitmap base
  +202    toprows[100]   first row with ink << 4 | number of rows stored
The bitmaps are a separate block (segment AUXFONT, copied to auxiliary
memory at startup): rows top..top+rows-1, 1 byte per row (width <= 8) or
2 bytes (lo, hi); bit 0 = leftmost pixel.
"""
import sys, importlib
sys.path.insert(0, __import__('os').path.dirname(__file__))

def compile_font(mod):
    G = mod.GLYPHS
    import font_sans
    widths, offs, tops, nrows, data = [], [], [], [], bytearray()
    base = 0
    for code in range(0x20, 0x84):
        rows = font_sans.SPECIAL[code] if code >= 0x7F else G.get(chr(code), G['?'])
        w = len(rows[0])
        assert len(rows) == 10 and w <= 16, chr(code)
        vals = [sum(1 << i for i, ch in enumerate(r) if ch == '#') for r in rows]
        ink = [i for i, v in enumerate(vals) if v]
        top = ink[0] if ink else 0
        n = (ink[-1] - top + 1) if ink else 0
        widths.append(w)
        tops.append(top)
        nrows.append(n)
        offs.append(base + len(data))
        for v in vals[top:top + n]:
            data.append(v & 0xFF)
            if w > 8:
                data.append(v >> 8)
    assert max(offs) < 1024 and max(widths) < 64 and max(tops) < 16 and max(nrows) < 16
    blob = (bytes([10, 8]) + bytes(w | (o >> 8) << 6 for w, o in zip(widths, offs))
            + bytes(o & 0xFF for o in offs) + bytes(t << 4 | n for t, n in zip(tops, nrows)))
    return blob, bytes(data)

def emit(name, blob):
    out = [f'_{name}:']
    for i in range(0, len(blob), 16):
        out.append('        .byte   ' + ','.join(f'${b:02X}' for b in blob[i:i + 16]))
    return '\n'.join(out)

if __name__ == '__main__':
    # metrics live in the language card; bitmaps in auxiliary memory
    parts = ['; generated by mkfonts.py - do not edit',
             '        .export _font_sans, _font_serif, _font_mono',
             '        .export _fbm_sans, _fbm_serif, _fbm_mono']
    tot = 0
    for name in ('sans', 'serif', 'mono'):
        blob, bm = compile_font(importlib.import_module('font_' + name))
        print(name, len(blob), len(bm), file=sys.stderr)
        tot += len(bm)
        parts.append('        .segment "LC"')
        parts.append(emit('font_' + name, blob))
        parts.append('        .segment "AUXFONT"')
        parts.append(emit('fbm_' + name, bm))
    print('bitmaps total', tot, file=sys.stderr)
    open(sys.argv[1], 'w').write('\n'.join(parts) + '\n')
