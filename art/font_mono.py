# RetroWrite II "Mono" - fixed-pitch typewriter companion to Sans.
# Every glyph sits in an 8-pixel cell (plus 1 pixel spacing).
import font_sans
from font_sans import g, B
CELL = 8

over = {
'A': g('..####..', '.##..##.', '##....##', '##....##', '########', '##....##', '##....##'),
'M': g('##....##', '###..###', '########', '##.##.##', '##....##', '##....##', '##....##'),
'O': g('..####..', '.##..##.', '##....##', '##....##', '##....##', '.##..##.', '..####..'),
'Q': g('..####..', '.##..##.', '##....##', '##....##', '##.#####', '.##..##.', '..######'),
'V': g('##....##', '##....##', '##....##', '.##..##.', '.##..##.', '..####..', '...##...'),
'W': g('##....##', '##....##', '##....##', '##.##.##', '########', '###..###', '##....##'),
'm': g('###.###.', '##.##.##', '##.##.##', '##.##.##', '##.##.##', top=3),
'w': g('##....##', '##....##', '##.##.##', '########', '.##..##.', top=3),
'@': g('.######.', '##....##', '##.#####', '##.##.##', '##.#####', '##......', '.######.'),
'I': g('######', '..##..', '..##..', '..##..', '..##..', '..##..', '######'),
'i': g('.##...', '......', '###...', '.##...', '.##...', '.##...', '######'),
'l': g('###...', '.##...', '.##...', '.##...', '.##...', '.##...', '######'),
'j': g('...##', '.....', '..###', '...##', '...##', '...##', '...##', '...##', '####.'),
'1': g('..##..', '.###..', '..##..', '..##..', '..##..', '..##..', '######'),
'r': g('###.###', '.###...', '.##....', '.##....', '######.', top=3),
'f': g('...####', '..##...', '######.', '..##...', '..##...', '..##...', '######.'),
't': g('..##...', '######.', '..##...', '..##...', '..##...', '...###.', top=2),
'.': g('##', '##', top=6),
}

def center(rows):
    w = len(rows[0])
    if w >= CELL:
        return rows
    l = (CELL - w) // 2
    r = CELL - w - l
    return [B * l + row + B * r for row in rows]

GLYPHS = {}
for ch, rows in font_sans.GLYPHS.items():
    rows = over.get(ch, rows)
    assert len(rows[0]) <= CELL, (ch, len(rows[0]))
    GLYPHS[ch] = center(rows)
GLYPHS[' '] = [B * CELL] * 10
NAME = 'Mono'
